/**
 * Буудлын нэрийг харьцуулахад бэлтгэх.
 *
 * Давхардлын trigram хайлт (§11.3) энэ хэлбэр дээр ажиллана. Хоёр алба хаагч
 * "Туушин зочид буудал" ба "ТУУШИН  Зочид Буудал" гэж бичсэн ч ижил гэж
 * тооцогдох ёстой.
 */
export function normalizeName(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFKC")
    // Цэг таслал нь бичих хэв маягаас хамаардаг — харьцуулалтад саад.
    .replace(/[«»"'`.,;:!?()\[\]{}\-–—_/\\]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 200);
}
