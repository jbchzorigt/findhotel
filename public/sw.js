/*
 * Хамгийн бага хэмжээний service worker.
 *
 * Зорилго нь ЗӨВХӨН нэг: Chrome/Android дээр "Апп суулгах" санал гаргах.
 * Тэр шалгуур нь `fetch` сонсогчтой байхыг шаарддаг.
 *
 * ЗОРИУД юу ч кэшлэхгүй. Оффлайн ажиллагаа нь хамрах хүрээнээс гадуур
 * (docs/PROJECT_SPEC.md §3), мөн кэшлэдэг SW нь хамгийн түгээмэл алдааны
 * эх үүсвэр болдог: хэрэглэгч хуучин хувилбарт гацаж, засвар хүрэхгүй.
 * Талбарын алба хаагч тийм байдалд орох ёсгүй.
 *
 * `respondWith` дуудахгүй тул браузер хүсэлтийг ердийн замаар боловсруулна.
 */

self.addEventListener("install", () => {
  // Шинэ хувилбарыг хүлээлгүй шууд идэвхжүүлнэ.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  // Нээлттэй байгаа бүх табыг шинэ SW-ийн удирдлагад шууд авна.
  event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", () => {
  // Санаатай хоосон: сонсогч байх нь суулгах шалгуурыг хангана,
  // хариу нь браузерын гарт үлдэнэ.
});
